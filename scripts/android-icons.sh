#!/usr/bin/env bash
# The desktop's icons (Lucide, apps/desktop/src/icons.rs) as Android vector
# drawables, res/drawable/ic_<name>.xml, so both apps draw the same glyphs.
# Stroked 24x24 paths in white; Compose tints them (Icon(painterResource(..), tint)).
set -euo pipefail
cd "$(dirname "$0")/.."
src=apps/desktop/src/icons.rs
out=apps/android/app/src/main/res/drawable
rm -f "$out"/ic_lucide_*.xml
perl -e '
    use strict;
    my ($src, $out) = @ARGV;
    open my $f, "<", $src or die; local $/; my $text = <$f>;
    my %body;
    while ($text =~ /pub const (\w+): &str =\s*r#"(.*?)"#;/gs) { $body{$1} = $2; }
    my $n = 0;
    while ($text =~ /"([a-z0-9-]+)" => (\w+),/g) {
        my ($name, $const) = ($1, $2);
        my $svg = $body{$const} or next;
        (my $id = $name) =~ s/-/_/g;
        my @paths;
        while ($svg =~ /<(path|circle|line|polyline)\s+([^>]*?)\/>/g) {
            my ($tag, $attrs) = ($1, $2);
            my %a = $attrs =~ /([\w-]+)="([^"]*)"/g;
            my ($d, $fill) = ("", 0);
            if ($tag eq "path") { $d = $a{d}; }
            elsif ($tag eq "circle") {
                my ($cx, $cy, $r) = ($a{cx}, $a{cy}, $a{r});
                $r = "0$r" if $r =~ /^\./;
                my $dia = $r * 2;
                $d = sprintf("M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 -%s,0", $cx - $r, $cy, $r, $r, $dia, $r, $r, $dia);
                $fill = 1 if ($a{fill} // "") eq "currentColor";
            }
            elsif ($tag eq "line") { $d = "M$a{x1},$a{y1} L$a{x2},$a{y2}"; }
            else { my @p = split /\s+/, $a{points}; $d = "M" . join(" L", @p); }
            my $paint = $fill
                ? q(android:fillColor="#FFFFFFFF")
                : q(android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round");
            push @paths, qq(    <path android:pathData="$d" $paint />);
        }
        open my $o, ">", "$out/ic_lucide_$id.xml" or die;
        print $o qq(<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android-icons.sh from the desktop icon "$name". -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n);
        print $o join("\n", @paths), "\n</vector>\n";
        close $o; $n++;
    }
    print "wrote $n icons\n";
' "$src" "$out"
